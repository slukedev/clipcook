/**
 * Extracts the Material Symbols this app uses from @material-symbols/svg-400
 * into src/components/ui/icon/icon-paths.ts as inline path data (outline +
 * fill variants). The output is checked in — rerun when adding an icon:
 *
 *   npm run generate:icons
 *
 * Inlining ~40 paths costs a few KB; the alternative (the variable icon
 * font) costs ~4 MB, a render-blocking request, and a FOUT of raw ligature
 * text. Icons render as plain <svg><path/></svg> in the Icon component.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

