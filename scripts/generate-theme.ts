/**
 * Generates the baseline M3 color theme (light + dark) from the brand seed
 * color into src/styles/theme/color.css. The output is checked in — rerun
 * only when the seed or the role set changes:
 *
 *   npm run generate:theme
 *
 * (Run through esbuild because @material/material-color-utilities ships
 * extensionless ESM imports that plain Node cannot resolve.)
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { argbFromHex } from '@material/material-color-utilities'
import { schemeFromSeed, schemeToCssDeclarations } from '../src/lib/theme/scheme'

const SEED = '#6750A4'

const light = schemeFromSeed(argbFromHex(SEED), false)
const dark = schemeFromSeed(argbFromHex(SEED), true)

const css = `/* Generated by scripts/generate-theme.ts — do not edit by hand.
 * Baseline M3 color scheme (tonal spot) from seed ${SEED}.
 * Per-recipe dynamic color overrides these variables in a scoped container. */

:root[data-theme='light'] {
    color-scheme: light;
${schemeToCssDeclarations(light, '    ')}
}

:root[data-theme='dark'] {
    color-scheme: dark;
${schemeToCssDeclarations(dark, '    ')}
}
`

// Run from the repo root (the npm script guarantees this).
const out = join(process.cwd(), 'src', 'styles', 'theme', 'color.css')
writeFileSync(out, css)
console.log(`Wrote ${out}`)
