/**
 * Writes the generated design tokens:
 *   src/styles/theme/color.css   brand scheme, light and dark, three contrast levels
 *   src/styles/theme/motion.css  M3 springs as CSS linear() curves, both motion schemes
 *
 *   npm run generate:theme
 *
 * Bundled with esbuild first because @material/material-color-utilities 0.4.0
 * ships extensionless ESM imports that plain Node cannot resolve.
 */
import { writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { CONTRASTS, type Contrast } from '../src/lib/theme/preference'
import { schemeDeclarations, schemeFromSeed } from '../src/lib/theme/scheme'
import { BRAND_PRIMARY_CHROMA, BRAND_SEED } from '../src/lib/theme/seed'
import { type MotionScheme, SPRING_TOKENS, SPRINGS, settleTime, springLinear } from '../src/lib/theme/springs'

const root = process.cwd()
const header = (what: string) => `/* Generated by scripts/generate-theme.ts. Do not edit by hand.\n * ${what} */\n`

function colorCss(): string {
    const blocks: string[] = []
    for (const contrast of CONTRASTS) {
        const light = schemeDeclarations(schemeFromSeed(BRAND_SEED, { contrast, primaryChroma: BRAND_PRIMARY_CHROMA }))
        const dark = schemeDeclarations(
            schemeFromSeed(BRAND_SEED, { dark: true, contrast, primaryChroma: BRAND_PRIMARY_CHROMA }),
        )
        const darkNested = dark.replaceAll('    --', '        --')
        const scope = (c: Contrast) => (c === 'standard' ? ':root' : `:root[data-contrast='${c}']`)
        const s = scope(contrast)
        blocks.push(
            `${s} {\n    color-scheme: light;\n${light}\n}`,
            `@media (prefers-color-scheme: dark) {\n    ${s}:not([data-theme='light']) {\n        color-scheme: dark;\n${darkNested}\n    }\n}`,
            `${s}[data-theme='dark'] {\n    color-scheme: dark;\n${dark}\n}`,
        )
    }
    return `${header(`TonalSpot 2025 from brand seed ${BRAND_SEED}, primary chroma ${BRAND_PRIMARY_CHROMA}. Dark follows the OS unless data-theme is set.`)}\n${blocks.join('\n\n')}\n`
}

const LEGACY_EASING = {
    linear: 'cubic-bezier(0, 0, 1, 1)',
    standard: 'cubic-bezier(0.2, 0, 0, 1)',
    'standard-accelerate': 'cubic-bezier(0.3, 0, 1, 1)',
    'standard-decelerate': 'cubic-bezier(0, 0, 0, 1)',
    emphasized: 'cubic-bezier(0.2, 0, 0, 1)',
    'emphasized-accelerate': 'cubic-bezier(0.3, 0, 0.8, 0.15)',
    'emphasized-decelerate': 'cubic-bezier(0.05, 0.7, 0.1, 1)',
    legacy: 'cubic-bezier(0.4, 0, 0.2, 1)',
}
const LEGACY_DURATION = {
    short: [50, 100, 150, 200],
    medium: [250, 300, 350, 400],
    long: [450, 500, 550, 600],
    'extra-long': [700, 800, 900, 1000],
}

function legacyDecl(): string {
    const lines = Object.entries(LEGACY_EASING).map(([k, v]) => `    --md-sys-motion-easing-${k}: ${v};`)
    for (const [k, values] of Object.entries(LEGACY_DURATION)) {
        values.forEach((ms, i) => {
            lines.push(`    --md-sys-motion-duration-${k}${i + 1}: ${ms}ms;`)
        })
    }
    return lines.join('\n')
}

function motionCss(): string {
    const decl = (scheme: MotionScheme, onlySpatial: boolean) =>
        SPRING_TOKENS.filter((t) => !onlySpatial || t.startsWith('spatial'))
            .map((token) => {
                const spec = SPRINGS[scheme][token]
                const ms = Math.round(settleTime(spec) * 1000)
                return `    --md-sys-motion-spring-${token}: ${springLinear(spec)};\n    --md-sys-motion-spring-${token}-duration: ${ms}ms;`
            })
            .join('\n')
    const reduced = SPRING_TOKENS.filter((t) => t.startsWith('spatial'))
        .map((t) => `        --md-sys-motion-spring-${t}-duration: 0ms;`)
        .join('\n')
    return `${header('M3 motion: springs sampled to their 0.1% settle time, plus the legacy easing and duration tokens.')}
/* Expressive is the default scheme; data-motion='standard' swaps the spatial springs. */
:root {
${decl('expressive', false)}

${legacyDecl()}
}

:root[data-motion='standard'] {
${decl('standard', true)}
}

/* Movement collapses to instant; effects springs (opacity, color) keep their short fades. */
@media (prefers-reduced-motion: reduce) {
    :root,
    :root[data-motion] {
${reduced}
    }
}
`
}

writeFileSync(join(root, 'src/styles/theme/color.css'), colorCss())
writeFileSync(join(root, 'src/styles/theme/motion.css'), motionCss())
console.log('Wrote color.css and motion.css')
