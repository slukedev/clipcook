import Head from 'next/head'
import styles from '@/styles/Home.module.scss'
import { useEffect, useState } from 'react';
import { Main } from '@/components/main';
import { Recipe } from '@/components/recipe';
import { Input } from '@/components/input';
import { Icon } from '@/components/icon';
import { Modal } from '@/components/modal';
import { Ripple } from '@/components/ripple';
import { Button } from '@/components/button';
import { AuthAction, useAuthUser, withAuthUser, withAuthUserTokenSSR, } from 'next-firebase-auth'
import { Spinner } from '@/components/spinner';
import { motion } from 'framer-motion';
import { useRouter } from 'next/router';

export function Home() {
  const user = useAuthUser()
  const [clipModalOpen, setClipModalOpen] = useState<boolean>(false);
  const [clipping, setClipping] = useState<boolean>(false);
  const [recipes, setRecipes] = useState<any>({});
  const [filteredRecipes, setFilteredRecipes] = useState<any>(-1);
  const [error, setError] = useState<string | false>(false);
  const router = useRouter();

  async function clip(e: React.FormEvent<HTMLFormElement>) {
    e.preventDefault();
    setClipping(true);
    setClipModalOpen(false);

    const url = (document.getElementById("clipurl") as HTMLInputElement).value;

    try {
      console.log(url)

      const idToken = await user.getIdToken();

      const headers = new Headers();
      headers.append("authorization", idToken || "");

      const fetchRequest = await fetch('/api/createrecipe?' + new URLSearchParams({
        url: url
      }), {
        method: 'POST',
        headers: headers
      });
      const fetchResponse = await fetchRequest.json()

      if (fetchResponse.message != "Success" || !fetchResponse.data) {
        setError(fetchResponse.data)
      }

      router.push(`/recipe/${fetchResponse.data}`);
    } catch (error: any) {
      setError(error.toString());
    }
  }

  function search(e: React.ChangeEvent<HTMLInputElement>) {
    if (e.target.value.length > 0) {
      const filtered = recipes.filter((recipe: any) => {
        const title = recipe.title.toLowerCase();
        const search = e.target.value.toLowerCase();

        recipe.boldIndexes = [];

        for (let i = 0; i < search.length; i++) {
          if (title.indexOf(search[i]) === -1) {
            return false;
          }

          recipe.boldIndexes.push(title.indexOf(search[i]));
        }

        return true;
      });

      setFilteredRecipes(filtered);
    } else {
      for (let i = 0; i < recipes.length; i++) {
        recipes[i].boldIndexes = [];
      }

      setFilteredRecipes(recipes);
    }
  }

  async function loadRecipes() {
    const idToken = await user.getIdToken();

    const headers = new Headers();
    headers.append("authorization", idToken || "");

    const req = await fetch("/api/getrecipes", {
      method: "GET",
      headers: headers
    });

    const res = await req.json();

    if (res.message != "Success") {
      setError(res.data);
      return;
    }

    for (let i = 0; i < res.data.length; i++) {
      res.data[i].boldIndexes = [];
    }

    setRecipes(res.data);
    setFilteredRecipes(res.data);
  }

  useEffect(() => {
    loadRecipes();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  return (
    <>
      <Head>
        <title>FoodMate</title>
        <meta name="description" content="Generated by create next app" />
        <meta name="viewport" content="width=device-width, initial-scale=1" />
        <link rel="icon" href="/favicon.ico" />
      </Head>
      <Main pageName="index" photoUrl={user.photoURL || undefined}>
        {
          error ? (
            <>
              <h1>Sorry, an error occurred.</h1>
              <p>{error}</p>
            </>
          ) : (
            <>
              {
                clipping ? (
                  <div className={styles.clipping}>
                    <h1>Clipping...</h1>
                    <svg width="198" height="357" viewBox="0 0 198 357" fill="none" xmlns="http://www.w3.org/2000/svg">
                      <path d="M189.5 75.5V266.5V266.5C178.116 374.746 20.573 374.726 9 266.5V266.5V63.5V63.5C17.6355 -8.74348 122.503 -8.7599 131 63.5V63.5V242.5V242.5C128.154 280.881 71.8465 280.881 69 242.5V242.5V75.5" stroke="black" strokeWidth="17" strokeLinecap="round" />
                    </svg>
                    <p>This may take a while. Then again, maybe it will not. It all depends...</p>
                  </div>
                ) : (
                  <>
                    <h1>Welcome, {user.displayName}!</h1>
                    {
                      filteredRecipes == -1 ? <></> : <Input onInput={search} label="Search" name="search" type="text" icon="search" />
                    }
                    <div className={styles.recipes}>
                      {
                        filteredRecipes == -1 ? (
                          <motion.div key="loading" initial={{ scale: 0.92, opacity: 0 }} animate={{ scale: 1, opacity: 1 }} transition={{ ease: "easeInOut", duration: 0.3 }} exit={{ opacity: 0 }} className={styles.loading}>
                            <h1>Loading recipes...</h1>
                            <Spinner />
                            <p>And chasing Belle off the counter...</p>
                          </motion.div>
                        ) : filteredRecipes.length === 0 ? (
                          <motion.div key="error" initial={{ scale: 0.92, opacity: 0 }} animate={{ scale: 1, opacity: 1 }} transition={{ ease: "easeInOut", duration: 0.3 }} exit={{ opacity: 0 }} className={styles.couldntFind}>
                            <Icon name="sound_detection_dog_barking" iconsize="128" />
                            <h1>Sorry, we couldn&apos;t find anything that matches</h1>
                            <p>We put our best searcher out and she came back with crumbs on her face, but no food to be found</p>
                          </motion.div>
                        ) : (
                          <motion.div key="recipes" initial={{ opacity: 0 }} animate={{ opacity: 1 }} transition={{ ease: "easeInOut", duration: 0.3 }} exit={{ opacity: 0 }}>
                            {
                              filteredRecipes.map((recipe: any) => {
                                return (
                                  <Recipe key={recipe.id} id={recipe.id.toString()} title={recipe.title} image={recipe.image} boldindexes={recipe.boldIndexes} />
                                )
                              })
                            }
                          </motion.div>
                        )
                      }
                    </div>
                  </>
                )
              }
            </>
          )
        }
      </Main>

      {
        error ? <></> : (
          <>
            {
              clipping ? null : (
                <div className={styles.fab}>
                  <Ripple feather="5px" speedms={500}>
                    <button onClick={() => setClipModalOpen(true)}>
                      <Icon name="add" iconsize="24" />
                    </button>
                  </Ripple>
                </div>
              )
            }


            <Modal opened={clipModalOpen} title="Clip URL" closefunction={() => setClipModalOpen(false)}>
              <form onSubmit={clip}>
                <Input type="url" label="URL" name="url" id="clipurl" icon="attachment" fullwidth autoComplete="off" />
                <div style={{ width: "100%", height: 24 }}></div>
                <Button>Clip</Button>
              </form>
            </Modal>
          </>
        )
      }
    </>
  )
}

export const getServerSideProps = withAuthUserTokenSSR({ whenUnauthed: AuthAction.REDIRECT_TO_LOGIN })()
export default withAuthUser({ whenUnauthedBeforeInit: AuthAction.REDIRECT_TO_LOGIN, })(Home)